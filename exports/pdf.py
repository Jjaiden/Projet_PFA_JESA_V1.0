    # ------------------------------------------------------------------
    # Logo discovery
    # ------------------------------------------------------------------

    def _locate_logos(
        self,
    ) -> Dict[str, Optional[Path]]:
        """
        Locate JESA and ENSAM logos from common project directories.
        """

        possible_bases = [
            Path(__file__).resolve().parents[1],
            Path.cwd(),
        ]

        try:
            possible_bases.insert(
                0,
                Path(
                    settings.backend.BASE_DIR
                ),
            )
        except Exception:
            pass

        logo_directories: List[Path] = []

        for base in possible_bases:

            logo_directories.extend(
                [
                    base / "assets" / "logos",
                    base / "assets" / "logo",
                    base / "assets",
                ]
            )

        jesa_path: Optional[Path] = None
        ensam_path: Optional[Path] = None

        jesa_candidates = [
            "logo_jesa.png",
            "jesa_logo.png",
            "JESA_logo.png",
            "jesa.png",
            "JESA.png",
            "logo_jesa.jpg",
            "jesa_logo.jpg",
            "JESA_logo.jpg",
        ]

        ensam_candidates = [
            "logo_ensam.png",
            "ensam_logo.png",
            "ENSAM_logo.png",
            "ensam.png",
            "ENSAM.png",
            "logo_ensam.jpg",
            "ensam_logo.jpg",
            "ENSAM_logo.jpg",
        ]

        for directory in logo_directories:

            if not directory.exists():
                continue

            if jesa_path is None:
                jesa_path = _find_logo(
                    directory,
                    jesa_candidates,
                )

            if ensam_path is None:
                ensam_path = _find_logo(
                    directory,
                    ensam_candidates,
                )

            if (
                jesa_path is not None
                and ensam_path is not None
            ):
                break

        # Final direct lookup
        if (
            jesa_path is None
            or ensam_path is None
        ):

            direct_path = (
                Path(__file__).resolve().parents[1]
                / "assets"
                / "logos"
            )

            if direct_path.exists():

                if jesa_path is None:
                    jesa_path = _find_logo(
                        direct_path,
                        jesa_candidates,
                    )

                if ensam_path is None:
                    ensam_path = _find_logo(
                        direct_path,
                        ensam_candidates,
                    )

        logger.info(
            "JESA logo path: %s",
            jesa_path,
        )

        logger.info(
            "ENSAM logo path: %s",
            ensam_path,
        )

        return {
            "jesa": jesa_path,
            "ensam": ensam_path,
        }

    # ------------------------------------------------------------------
    # Header / Footer
    # ------------------------------------------------------------------

    def _draw_header_footer(
        self,
        canvas,
        doc,
        title_prefix: str = "",
    ):
        """
        Draw the page header/footer.

        IMPORTANT:
        The logos occupy the upper header area.
        The textual header is deliberately positioned BELOW
        the logos so that the two elements never overlap.
        """

        canvas.saveState()

        width, height = A4

        # ==============================================================
        # HEADER GEOMETRY
        # ==============================================================

        left_margin = 12 * mm
        right_margin = 12 * mm

        # Logo dimensions
        logo_width = 80
        logo_height = 40

        # Logo bottom Y position
        logo_y = height - 16 * mm

        # Text is deliberately BELOW the logos.
        text_y = height - 24 * mm

        # Separator is below header text.
        separator_y = height - 27 * mm

        # ==============================================================
        # JESA LOGO
        # ==============================================================

        if self._logo_paths.get("jesa"):

            try:

                img = ImageReader(
                    str(
                        self._logo_paths["jesa"]
                    )
                )

                canvas.drawImage(
                    img,
                    left_margin,
                    logo_y,
                    width=logo_width,
                    height=logo_height,
                    preserveAspectRatio=True,
                    mask="auto",
                )

            except Exception as exc:

                logger.warning(
                    "Could not draw JESA logo: %s",
                    exc,
                )

        # ==============================================================
        # ENSAM LOGO
        # ==============================================================

        if self._logo_paths.get("ensam"):

            try:

                img = ImageReader(
                    str(
                        self._logo_paths["ensam"]
                    )
                )

                canvas.drawImage(
                    img,
                    width - 92 * mm,
                    logo_y,
                    width=logo_width,
                    height=logo_height,
                    preserveAspectRatio=True,
                    mask="auto",
                )

            except Exception as exc:

                logger.warning(
                    "Could not draw ENSAM logo: %s",
                    exc,
                )

        # ==============================================================
        # HEADER TEXT
        # ==============================================================
        #
        # THIS IS THE FIX:
        #
        # Previously:
        #     height - 9 mm
        #
        # which placed the text alongside/over the logos.
        #
        # Now:
        #     height - 24 mm
        #
        # which places the text below the logos.
        # ==============================================================

        canvas.setFont(
            "Helvetica-Bold",
            6.5,
        )

        canvas.setFillColor(
            JESA_DARK
        )

        canvas.drawString(
            left_margin,
            text_y,
            "JESA DMAT",
        )

        canvas.setFont(
            "Helvetica",
            6.5,
        )

        canvas.setFillColor(
            GREY_600
        )

        header_right_text = (
            f"{title_prefix} — "
            "Industrial Digital Maturity Assessment"
        )

        canvas.drawRightString(
            width - right_margin,
            text_y,
            header_right_text,
        )

        # ==============================================================
        # HEADER SEPARATOR
        # ==============================================================

        canvas.setStrokeColor(
            GREY_200
        )

        canvas.setLineWidth(
            0.5
        )

        canvas.line(
            left_margin,
            separator_y,
            width - right_margin,
            separator_y,
        )

        # ==============================================================
        # FOOTER
        # ==============================================================

        canvas.setStrokeColor(
            GREY_200
        )

        canvas.line(
            left_margin,
            8 * mm,
            width - right_margin,
            8 * mm,
        )

        canvas.setFont(
            "Helvetica",
            5.8,
        )

        canvas.setFillColor(
            GREY_600
        )

        canvas.drawString(
            left_margin,
            4.5 * mm,
            "JESA DMAT • Digital Maturity Assessment",
        )

        canvas.drawRightString(
            width - right_margin,
            4.5 * mm,
            f"Page {doc.page}",
        )

        canvas.restoreState()


