# ------------------------------------------------------------------------------

def _get(
    obj: Any,
    key: str,
    default: Any = None,
) -> Any:
    """
    Read a value from either:
        - a Mapping/dictionary
        - an object attribute
    """

    if obj is None:
        return default

    if isinstance(obj, Mapping):
        return obj.get(key, default)

    return getattr(obj, key, default)


def _safe_str(
    value: Any,
    default: str = "",
) -> str:
    if value is None:
        return default

    return str(value)


def _safe_float(
    value: Any,
    default: float = 0.0,
) -> float:
    try:
        return (
            float(value)
            if value is not None
            else default
        )
    except (TypeError, ValueError):
        return default


def _format_number(
    value: Any,
    decimals: int = 1,
) -> str:
    if value is None:
        return "—"

    try:
        return f"{float(value):.{decimals}f}"
    except (TypeError, ValueError):
        return str(value)


def _normalize_priority(
    priority: Any,
) -> str:
    if priority is None:
        return ""

    mapping = {
        "critical": "Critical",
        "critique": "Critical",

        "high": "High",
        "haute": "High",

        "medium": "Medium",
        "moyenne": "Medium",

        "low": "Low",
        "faible": "Low",

        "very low": "Very Low",
        "très faible": "Very Low",
        "tres faible": "Very Low",
    }

    normalized = str(priority).strip().lower()

    return mapping.get(
        normalized,
        str(priority),
    )


def _priority_color(
    priority: Any,
) -> colors.Color:
    return PRIORITY_COLORS.get(
        _normalize_priority(priority),
        GREY_600,
    )


def _as_list(
    value: Any,
) -> List[Any]:
    if value is None:
        return []

    if isinstance(value, list):
        return value

    if isinstance(value, tuple):
        return list(value)

    if isinstance(value, Mapping):
        return list(value.values())

    return [value]


def _escape_xml(
    value: Any,
    default: Any = None,
) -> str:
    text = _safe_str(
        value,
        _safe_str(default),
    )

    return (
        text
        .replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
    )


# ------------------------------------------------------------------------------
# Logo helpers
# ------------------------------------------------------------------------------

def _find_logo(
    directory: Path,
    candidates: List[str],
) -> Optional[Path]:
    """
    Find a logo using exact filename matching first,
    followed by case-insensitive matching.
    """

    if not directory.exists():
        return None

    if not directory.is_dir():
        return None

    # Exact match
    for filename in candidates:

        path = directory / filename

        if path.exists() and path.is_file():
            return path

    # Case-insensitive fallback
    candidate_names = {
        name.lower()
        for name in candidates
    }

    try:

        for path in directory.iterdir():

            if (
                path.is_file()
                and path.name.lower()
                in candidate_names
            ):
                return path

    except OSError:
        return None

    return None


