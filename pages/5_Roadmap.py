def _render_export_section() -> None:
    """
    Display export format selection and download buttons.

    CORRECTION : layout fixe en 3 colonnes + type="primary" pour éviter
    le rendu "blanc sur blanc" des boutons de download.
    """

    st.markdown("## Export Assessment")

    st.caption(
        "Select the deliverables you want to generate for this assessment."
    )

    backend_results = st.session_state.get("backend_results")

    if not backend_results:
        st.warning(
            "No assessment data is available for export."
        )
        return

    selected_formats = st.multiselect(
        "Export formats",
        options=["pdf", "excel", "report"],
        default=["pdf"],
        format_func=lambda value: {
            "pdf": "PDF Report",
            "excel": "Excel Workbook",
            "report": "Management Report",
        }.get(value, value.upper()),
        key="roadmap_export_formats",
    )

    if not selected_formats:
        st.info(
            "Select at least one export format."
        )
        return

    if st.button(
        "GENERATE SELECTED EXPORTS",
        key="generate_roadmap_exports",
        use_container_width=True,
        type="primary",
    ):

        try:

            export_paths = export_selected_assessment(
                backend_results,
                selected_formats,
            )

            st.session_state["latest_export_paths"] = {
                key: str(path)
                for key, path in export_paths.items()
            }

            st.success(
                "Selected export files generated successfully."
            )

            st.rerun()

        except Exception as exc:

            st.error(
                f"Export generation failed: {exc}"
            )

    export_paths = st.session_state.get(
        "latest_export_paths",
        {},
    )

    if not export_paths:
        return

    st.markdown("### Available Downloads")

    # ═══════════════════════════════════════════════════════════════
    # CORRECTION : layout fixe en 3 colonnes + type="primary"
    # pour éviter le rendu "blanc sur blanc" des boutons de download.
    # ═══════════════════════════════════════════════════════════════
    cols = st.columns(3)

    format_meta = {
        "pdf": (
            "DOWNLOAD Scoring Report",
            "application/pdf",
            "pdf",
        ),
        "excel": (
            "DOWNLOAD EXCEL",
            "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
            "xlsx",
        ),
        "report": (
            "DOWNLOAD Global Report",
            "application/pdf",
            "pdf",
        ),
    }

    assessment_id = (
        backend_results.get("assessment_id")
        or "assessment"
    )

    for idx, (fmt_key, (label, mime, ext)) in enumerate(
        format_meta.items()
    ):

        path = export_paths.get(fmt_key)

        with cols[idx]:

            if not path:
                st.caption(
                    f"— {label} not generated —"
                )
                continue

            path_obj = Path(path)

            if not path_obj.exists():
                st.warning(
                    f"{label}: file missing"
                )
                continue

            try:
                file_data = path_obj.read_bytes()
                if len(file_data) == 0:
                    st.warning(
                        f"{label}: empty file"
                    )
                    continue
            except Exception:
                st.error(
                    f"{label}: read error"
                )
                continue

            filename = (
                f"JESA_DMAT_{assessment_id}.{ext}"
            )

            st.download_button(
                label=label,
                data=file_data,
                file_name=filename,
                mime=mime,
                key=f"roadmap_dl_{fmt_key}",
                use_container_width=True,
                type="primary",
            )


